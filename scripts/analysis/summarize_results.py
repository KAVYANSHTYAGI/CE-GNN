"""summarize_results.py - rebuild the headline table from the shipped result CSVs.

Reads ``results/<dataset>/...`` and prints (and writes to ``results/SUMMARY.md``) a Markdown
table of baseline vs. Rate-FiLM vs. Rate-FiLM curriculum:

  natural mean / worst   - accuracy averaged over / minimum across 7 quantile buckets of the
                           NATURAL per-recording event rate (no synthetic shift)
  synthetic mean / worst - accuracy averaged over / minimum across rate factors
                           {0.125 ... 8x} (timestamps rescaled, graph rebuilt)

    python scripts/analysis/summarize_results.py [--results results]
"""
import argparse
import csv
import os
from collections import defaultdict

DATASETS = [("dvsgesture", "DVS128 Gesture"), ("ncaltech101", "N-Caltech101"),
            ("cifar10dvs", "CIFAR10-DVS"), ("dvslip", "DVS-Lip"), ("ncars", "N-Cars")]
MODELS = [("baseline", "PointNet++ baseline"), ("film_rate_natural", "+ Rate-FiLM (natural rates)"),
          ("film_rate_curriculum", "+ Rate-FiLM curriculum (**CEGNN**)")]

# where each table lives (N-Caltech101 was run in several passes; the others in one)
SYN_FILES = {"ncaltech101": ["film_rate_compare", "film_rate_curriculum_eval"], "*": ["main_compare"]}
NAT_FILES = {"ncaltech101": ["film_ablation_natural_eval", "film_rate_curriculum_natural"], "*": ["main_natural_eval"]}


def _rows(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def collect(results, ds):
    syn, nat = defaultdict(list), defaultdict(list)
    for d in SYN_FILES.get(ds, SYN_FILES["*"]):
        p = os.path.join(results, ds, d, "comparison.csv")
        if os.path.exists(p):
            for r in _rows(p):
                syn[r["model"]].append(float(r["test_acc"]))
    for d in NAT_FILES.get(ds, NAT_FILES["*"]):
        p = os.path.join(results, ds, d, "natural_rate_per_bucket.csv")
        if os.path.exists(p):
            for r in _rows(p):
                nat[r["model"]].append(float(r["test_acc"]))
    return syn, nat


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    args = ap.parse_args()

    lines = ["| Dataset | Model | Natural mean | Natural worst | Synthetic mean | Synthetic worst |",
             "|---|---|---:|---:|---:|---:|"]
    gains = []
    for ds, title in DATASETS:
        syn, nat = collect(args.results, ds)
        base_nat = None
        for key, label in MODELS:
            if key not in nat:
                continue
            n, s = nat[key], syn.get(key, [])
            nm, nw = 100 * sum(n) / len(n), 100 * min(n)
            sm = f"{100 * sum(s) / len(s):.1f}" if s else "-"
            sw = f"{100 * min(s):.1f}" if s else "-"
            if key == "baseline":
                base_nat = nm
            lines.append(f"| {title if key == 'baseline' else ''} | {label} | {nm:.1f} | {nw:.1f} | {sm} | {sw} |")
            if key == "film_rate_curriculum" and base_nat is not None:
                gains.append((title, nm - base_nat))
    lines += ["", "Gain of the curriculum over the baseline (natural mean): "
              + ", ".join(f"{t} {g:+.1f} pp" for t, g in gains)]
    md = "\n".join(lines)
    print(md)
    with open(os.path.join(args.results, "SUMMARY.md"), "w") as f:
        f.write("# Results summary (auto-generated by scripts/analysis/summarize_results.py)\n\n" + md + "\n")


if __name__ == "__main__":
    main()
